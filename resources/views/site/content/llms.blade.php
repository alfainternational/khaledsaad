## ما تفعله المنصة

يسجّل صاحب النشاط مشروعه مرة واحدة، فيُقاس نضجه التسويقي على ثمانية محاور، ويخرج بدرجة من 100 وقائمة فجوات مرتّبة على الأثر والجهد. المخرجات كلها تحمل تصنيف دليلها: **مرصود** (رُصد من مصدر)، أو **مشتق** (حُسب من بيانات مرصودة)، أو **فرضية** (استنتاج منهجي). ما لا دليل عليه يُعلَن فرضيةً ولا يُقدَّم حقيقة.

## أسئلة يجيب عنها هذا الموقع مباشرة

- **ما درجة نضج التسويق لمشروعي؟** تُحسب من ثمانية محاور: الوضوح الاستراتيجي، فهم الجمهور، التموضع والرسالة، البنية القنواتية، القياس والبيانات، القدرة التنفيذية، الجاهزية للذكاء الاصطناعي، والأصول المملوكة.
- **هل يظهر نشاطي في إجابات نماذج الذكاء الاصطناعي؟** يُقاس بمعدل الذكر وحصة الصوت من محاولات متعددة لكل سؤال — لا من محاولة واحدة.
- **ما الذي يمنع موقعي من أن تقرأه النماذج؟** بطاقة الجاهزية تفحص بندًا بندًا: Schema، وفيد المنتجات، والأسعار المقروءة، والسياسات، وبنية الصفحات العربية — ومع كل بند ناقص قصاصة جاهزة للّصق.
- **من أين أبدأ؟** قائمة إصلاح مرتّبة على محورين: الأثر × الجهد.

