<h2>4. الباقات والاشتراك والدفع</h2>
<ul>
<li>تختلف الميزات المتاحة حسب الباقة المختارة، وتُحدَّد صلاحيات كل باقة في <a href="/pricing">صفحة التسعير</a>.</li>
<li>الاشتراكات شهرية أو سنوية حسب اختيارك، وتتجدد تلقائياً ما لم تُلغِ التجديد قبل نهاية الفترة الحالية.</li>
<li>جميع الأسعار بالعملة المحددة وشاملة أو غير شاملة للضريبة حسب المبيّن عند الشراء.</li>
<li>يتم تحصيل الدفعات عبر مزود دفع معتمد، ولا تُحفظ بيانات البطاقات على خوادم المنصة.</li>
<li>سياسة الاسترداد: تخضع المبالغ المدفوعة لسياسة عدم الاسترداد بعد مرور 14 يوماً من تاريخ الدفع، ما لم يُتفق خلاف ذلك أو يفرضه النظام المعمول به.</li>
</ul>

<h2>5. الترقية والتخفيض وإلغاء الاشتراك</h2>
<p>يمكنك ترقية باقتك أو تخفيضها أو إلغاؤها من إعدادات الحساب في أي وقت. يسري الإلغاء في نهاية الفترة المدفوعة الحالية، ويحتفظ المستخدم بوصوله حتى ذلك التاريخ. الميزات التي تعتمد على باقة أعلى تتوقف عند التخفيض مع الحفاظ على البيانات لفترة محددة.</p>

<h2>6. الاستخدام المقبول</h2>
<p>يلتزم المستخدم بعدم استخدام المنصة في أي مما يلي:</p>
<ul>
<li>أي نشاط غير قانوني أو مخالف للأنظمة المعمول بها في المملكة العربية السعودية.</li>
<li>انتهاك حقوق الملكية الفكرية لأي طرف ثالث.</li>
<li>إنتاج أو نشر محتوى يُحرّض على الكراهية أو العنف أو التمييز.</li>
<li>محاولة اختراق المنصة أو تجاوز حدود الاستخدام أو الهندسة العكسية للكود.</li>
<li>استخدام أدوات آلية (Bots, Scrapers) لاستخراج البيانات بدون إذن كتابي.</li>
<li>إعادة بيع خدمات المنصة أو السماح لأطراف غير مخولة باستخدام حسابك.</li>
</ul>
<p>أي مخالفة قد تؤدي إلى تجميد أو إنهاء الحساب فوراً دون استرداد المبالغ المدفوعة.</p>

<h2>7. ملكية المحتوى</h2>
<ul>
<li><strong>محتوى المستخدم:</strong> تظل جميع حقوق الملكية الفكرية للمحتوى الذي تُنشئه أو تُدخله في المنصة ملكاً لك. تمنحنا فقط ترخيصاً محدوداً لاستضافته ومعالجته لتقديم الخدمة.</li>
<li><strong>مخرجات الاستوديو الذكي:</strong> المخرجات المُولّدة بواسطة الذكاء الاصطناعي بناءً على مدخلاتك تعود ملكيتها لك، مع التزامك بالاستخدام المسؤول لها.</li>
<li><strong>محتوى المنصة:</strong> الأدوات، القوالب، الواجهات، التصاميم، والشفرة البرمجية تعود ملكيتها الكاملة لنا، ولا يجوز نسخها أو تعديلها أو إعادة توزيعها بدون إذن كتابي.</li>
</ul>

<h2>8. الاستوديو الذكي والذكاء الاصطناعي</h2>
<ul>
<li>مخرجات الذكاء الاصطناعي تُقدَّم «كما هي» وقد تحتوي على أخطاء أو معلومات غير دقيقة. المستخدم مسؤول عن مراجعة المخرجات قبل استخدامها.</li>
<li>المنصة غير مسؤولة عن أي قرار تجاري أو قانوني يُتخذ بناءً على مخرجات الذكاء الاصطناعي وحدها.</li>
<li>يُحظر استخدام الاستوديو لتوليد محتوى مخادع أو انتحال شخصية أو تضليل.</li>
<li>تُحتسب كل عملية توليد من رصيد AI credits الخاص بباقتك.</li>
