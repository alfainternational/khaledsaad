    /**
     * @return array{text: string, source: string}|null
     */
    public function forField(string $fieldKey, ?Project $project = null): ?array
    {
        // الرقم الحيّ من السوق يسبق الجدول الإرشادي حين يتوفر، ويسقط إليه بصمت حين لا يتوفر.
        if ($this->live->isAvailable()) {
            $liveValue = $this->live->forField($fieldKey, $project);

            if ($liveValue !== null) {
                return $liveValue;
            }
        }

        $entry = self::TABLE[$fieldKey] ?? null;

        if ($entry === null) {
            return null;
        }

        $model = $project?->profile?->business_model;
        $range = $entry['by_model'][$model] ?? $entry['default'];

        return [
            'text' => trim($range.' '.($entry['rule'] ?? '')),
            'source' => 'مدى إرشادي شائع في السوق — تقدير للمقارنة لا رقم رسمي · تحديث يوليو 2026',
        ];
    }

