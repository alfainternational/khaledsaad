<?php

namespace App\Modules\AiReadiness\Contracts;

/**
 * محرك إجابات: نموذج لغوي يُسأل سؤال مشترٍ ويُقرأ جوابه.
 *
 * كل مزوّد خارجي خلف عقد (§٤.١). السبب هنا أقوى من المعتاد: هذه أول قدرة
 * بتكلفة متغيرة، وربطها بمزوّد بعينه يعني أن تغيير السعر أو المنع الجغرافي
 * يوقف المنتج. العقد يجعل التبديل تغييرَ سطر في الحاوية.
 *
 * والأهم: العقد يجعل الاختبار ممكنًا بلا دفع. مزوّد وهمي يعيد نصًّا ثابتًا
 * يكفي لاختبار كل ما فوقه — وما فوقه هو كل ما يُباع.
 */
interface AnswerEngine
{
    /**
     * سؤال واحد، محاولة واحدة.
     *
     * المحاولات لا تُجمَّع هنا عمدًا: كل محاولة استدعاء مستقل بحرارة كاملة،
     * وطلب «ثلاث إجابات» في نداء واحد يعطي ثلاث صيغ لجواب واحد لا ثلاث
     * عيّنات — فينهار `consistency` وهو أصلًا قياسٌ للتذبذب.
     *
     * @return array{text: string, latency_ms: int, cost_usd: float}
     */
    public function ask(string $question, string $locale = 'ar'): array;

    public function name(): string;

    public function model(): string;
}
