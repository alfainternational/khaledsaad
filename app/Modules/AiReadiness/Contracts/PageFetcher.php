<?php

namespace App\Modules\AiReadiness\Contracts;

/**
 * جالب الصفحات.
 *
 * خلف عقد لسببين: أن تُختبر قواعد التدقيق ببيانات ثابتة بلا شبكة، وأن يبقى
 * تبديل المزوّد (خادم داخلي، وكيل، خدمة زحف) تغييرًا في مكان واحد.
 */
interface PageFetcher
{
    /**
     * يعيد جسم الاستجابة، أو null إن تعذّر الوصول.
     *
     * لا يرمي عند فشل الشبكة: تعذّر الجلب حالة متوقّعة في التدقيق لا خطأ
     * برمجي، والتمييز بين «فحصنا فلم نجد» و«لم نستطع الفحص» هو ما يمنع
     * التقرير من اتهام موقع سليم.
     */
    public function get(string $url): ?string;
}
