    /**
     * القالب الأخير: التوصية التي لا يُعرف موضوعها تصير قائمة تنفيذ من
     * خطواتها نفسها. ليست مثالًا جاهزًا للنسخ، لكنها ليست فراغًا — والمستخدم
     * يعرف من مصدر المثال أنها الحد الأدنى لا الأفضل.
     *
     * @param  array<int, string>  $steps
     */
    private function checklist(string $title, ExampleContext $context, array $steps): WorkedExample
    {
        $lines = ['ابدأ بهذه الخطوات بالترتيب، ولا تنتقل لخطوة قبل إنهاء ما قبلها:', ''];

        $steps = array_values(array_filter(array_map(
            fn ($step) => trim((string) $step),
            $steps,
        ), fn (string $step) => $step !== ''));

        if ($steps === []) {
            $steps = $this->fallbackSteps();
        }

        foreach ($steps as $index => $step) {
            $lines[] = ($index + 1).') '.$step;
        }

        $lines[] = '';
        $lines[] = "الناتج المطلوب في نهاية الأسبوع: [شيء واحد ملموس يخص «{$title}» يمكنك أن تريه لغيرك]";

        return new WorkedExample(
            kind: 'checklist',
            title: 'خطوات تنفيذ مرتّبة لهذه التوصية',
