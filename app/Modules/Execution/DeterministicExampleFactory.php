    public function build(string $title, string $description, ExampleContext $context, array $steps = []): WorkedExample
    {
        return match ($this->topic($title.' '.$description)) {
            'tracking' => $this->tracking($context),
            'reviews' => $this->reviews($context),
            'email' => $this->email($context),
            'ads' => $this->ads($context),
            'landing' => $this->landing($context),
            'offer' => $this->offer($context),
            'positioning' => $this->positioning($context),
            'audience' => $this->audience($context),
            'content' => $this->content($context),
            'outreach' => $this->outreach($context),
            default => $this->checklist($title, $context, $steps),
        };
    }

    private function topic(string $haystack): ?string
    {
        foreach (self::TOPICS as $topic => $words) {
            foreach ($words as $word) {
                if (mb_stripos($haystack, $word) !== false) {
                    return $topic;
                }
            }
        }

        return null;
    }

