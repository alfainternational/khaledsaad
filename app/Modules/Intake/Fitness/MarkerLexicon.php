    {
        return match ($want) {
            FieldExpectation::WHO => 'من هم تحديدًا (مهنة أو دور أو نوع منشأة)',
            FieldExpectation::WHERE => 'أين هم (مدينة أو منطقة أو نطاق)',
            FieldExpectation::NEED => 'لماذا يشترون (الدافع أو الوجع)',
            FieldExpectation::NUMBER => 'رقم يحدّد الحجم أو المدة',
            FieldExpectation::SEGMENTS => 'أكثر من عنصر واحد مفصول',
            FieldExpectation::CHANNEL => 'القناة أو المنصة بالاسم',
            FieldExpectation::MONEY => 'المقابل المالي أو الميزانية',
            FieldExpectation::CONTRAST => 'مقارنة صريحة بما يقدّمه غيرك',
            default => $want,
        };
    }

    public static function vagueMatch(string $value): ?string
    {
        $haystack = ArabicText::normalize($value);

        foreach (self::VAGUE as $phrase) {
            if (str_contains($haystack, ArabicText::normalize($phrase))) {
                return $phrase;
            }
        }

        return null;
    }
