    /**
     * @return array<string, mixed>|null
     */
    public static function find(string $key): ?array
    {
        foreach (self::fields() as $field) {
            if ($field['key'] === $key) {
                return self::resolveOptions($field);
            }
        }

        return null;
    }

    /**
     * نوع إجابة الحقل، أو `null` لما لا يُقاس ولما ليس من الملف أصلًا.
     *
     * يعيد `null` لغير المقيس بدل أن يعيد نوعًا لا يُقاس: الفرق بين «ليس حقلًا
     * نعرفه» و«حقل قررنا ألّا نحكم عليه» يجب أن يبقى ظاهرًا لمن يقرأ المستدعي.
     */
    public static function measurableType(string $key): ?string
    {
        $field = self::find($key);

        return $field !== null && ($field['measured'] ?? false)
            ? (string) $field['type']
            : null;
    }

    /**
     * @param  array<string, mixed>  $field
     * @return array<string, mixed>
     */
    private static function resolveOptions(array $field): array
    {
        /*
         * القطاعات مصدرها `Sector` لا نسخة ثانية هنا: قائمة تُنسخ قائمتان
         * تتباعدان. والتلميح يُضمّ إلى التسمية لأن اختيار القطاع في المنصة يفتح
         * أسئلة وفحوصات مختلفة — فمن لا يعرف ما الذي يشمله «التجارة الإلكترونية»
         * يختار خطأً ويُقاس بمعايير قطاع ليس قطاعه.
         */
        if (($field['options'] ?? null) === 'sector') {
            $field['options'] = array_map(
                fn (array $option) => [
                    'value' => $option['value'],
                    'label' => trim($option['label'].(empty($option['hint']) ? '' : ' — '.$option['hint'])),
                ],
                Sector::options(),
            );
        }

        return $field;
    }
