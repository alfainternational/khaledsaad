    /**
     * @return array<string, mixed>
     */
    public function for(Tool|string $tool): array
    {
        $code = $tool instanceof Tool ? $tool->code : $tool;

        return $this->definitions()[$code] ?? $this->fallbackBlueprint($tool);
    }

    /**
     * المفتاح التقني → عنوان الحقل والتلميح (لتحسين برومبت الاقتراحات والتحليل).
     *
     * @return array<string, array{label: string, answer_tip: string}>
     */
    public function fieldLabelMap(string $toolCode, ?string $mode = null): array
    {
        $bp = $this->for($toolCode);
        $modes = $bp['modes'] ?? [];

        if ($mode !== null && $mode !== '' && isset($modes[$mode]['fields'])) {
            return $this->fieldsToLabelMap($modes[$mode]['fields']);
        }

        $map = [];
        foreach ($modes as $modeData) {
            foreach ($modeData['fields'] ?? [] as $field) {
                $key = (string) ($field['key'] ?? '');
                if ($key === '' || isset($map[$key])) {
                    continue;
                }
                $map[$key] = [
                    'label' => (string) ($field['label'] ?? $key),
                    'answer_tip' => (string) ($field['answer_tip'] ?? ''),
                ];
            }
        }

        return $map;
    }

    /**
     * @param  array<int, array<string, mixed>>  $fields
     * @return array<string, array{label: string, answer_tip: string}>
     */
    private function fieldsToLabelMap(array $fields): array
    {
        $map = [];
        foreach ($fields as $field) {
            $key = (string) ($field['key'] ?? '');
            if ($key === '') {
                continue;
            }
            $map[$key] = [
                'label' => (string) ($field['label'] ?? $key),
                'answer_tip' => (string) ($field['answer_tip'] ?? ''),
            ];
        }

        return $map;
    }

