    /**
     * @param  array<string, array<string, mixed>>  $modes
     * @return array<string, mixed>
     */
    private function makeBlueprint(
        string $intro,
        string $why,
        string $when,
        string $outcome,
        string $aiRole,
        string $resultLabel,
        array $modes,
    ): array {
        return [
            'intro' => $intro,
            'why' => $why,
            'when' => $when,
            'outcome' => $outcome,
            'ai_role' => $aiRole,
            'result_label' => $resultLabel,
            'modes' => $modes,
        ];
    }

    /**
     * @param  array<int, array<string, mixed>>  $fields
     * @return array<string, mixed>
     */
    private function mode(string $label, string $description, array $fields): array
    {
        return [
            'label' => $label,
            'description' => $description,
            'fields' => $fields,
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function textField(string $key, string $label, string $placeholder = ''): array
    {
        return $this->enrichField([
            'key' => $key,
            'label' => $label,
            'type' => 'text',
            'placeholder' => $placeholder,
        ]);
    }

    /**
     * @return array<string, mixed>
     */
    private function selectField(string $key, string $label, array $options): array
    {
        return $this->enrichField([
            'key' => $key,
            'label' => $label,
            'type' => 'select',
            'options' => $options,
        ]);
    }

    /**
     * @param  array<string, mixed>  $field
     * @return array<string, mixed>
     */
    private function enrichField(array $field): array
    {
        $tip = $this->answerTipFor(
            (string) ($field['key'] ?? ''),
            (string) ($field['label'] ?? ''),
            (string) ($field['placeholder'] ?? ''),
            (string) ($field['type'] ?? 'text'),
        );

        return $field + [
            'answer_tip' => $tip,
        ];
    }

    private function answerTipFor(string $key, string $label, string $placeholder, string $type): string
    {
        if ($type === 'select') {
            return 'اختر الخيار الأقرب للواقع الحالي، لا الخيار الذي تتمنى الوصول إليه لاحقاً.';
        }

        $haystack = mb_strtolower($key.' '.$label.' '.$placeholder);

        return match (true) {
            str_contains($haystack, 'audience'),
            str_contains($haystack, 'customer'),
            str_contains($haystack, 'segment'),
            str_contains($haystack, 'لمن'),
            str_contains($haystack, 'العميل'),
            str_contains($haystack, 'الشريحة') => 'اذكر شريحة يمكن تخيلها وبيعها فعلاً، لا وصفاً عاماً مثل الجميع أو المشاريع الصغيرة فقط.',
            str_contains($haystack, 'goal'),
            str_contains($haystack, 'result'),
            str_contains($haystack, 'outcome'),
            str_contains($haystack, 'الهدف'),
            str_contains($haystack, 'النتيجة') => 'أفضل إجابة هنا تذكر نتيجة قابلة للملاحظة ويفضل معها زمن أو رقم أو معيار نجاح واضح.',
            str_contains($haystack, 'problem'),
            str_contains($haystack, 'bottleneck'),
            str_contains($haystack, 'obstacle'),
            str_contains($haystack, 'المشكلة'),
            str_contains($haystack, 'العائق'),
            str_contains($haystack, 'المعطل') => 'صف المشكلة مع أثرها المباشر وسببها أو توقيتها، لا تكتب عنواناً عاماً فقط.',
            str_contains($haystack, 'difference'),
            str_contains($haystack, 'unique'),
            str_contains($haystack, 'الميزة'),
            str_contains($haystack, 'التميّز'),
            str_contains($haystack, 'التمييز') => 'اذكر طريقة أو زاوية أو آلية مختلفة فعلاً، لا مجرد اسم خدمة متكرر في السوق.',
