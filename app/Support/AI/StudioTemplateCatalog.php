    /**
     * @return array<int, array<string, mixed>>
     */
    public function templates(): array
    {
        return [
            ...$this->marketingTemplates(),
            ...$this->brandTemplates(),
        ];
    }

    /**
     * @return array<string, array<string, mixed>>
     */
    public function definitions(): array
    {
        return collect($this->templates())
            ->mapWithKeys(fn (array $template): array => [
                $template['code'] => $template['registry_definition'] ?? [],
            ])
            ->all();
    }

    /**
     * @return array<int, array<string, mixed>>
     */
    public function seededTemplates(): array
    {
        return collect($this->templates())
            ->map(fn (array $template): array => collect($template)
                ->except(['registry_definition'])
                ->all())
            ->all();
    }

