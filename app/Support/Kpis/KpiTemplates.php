<?php

namespace App\Support\Kpis;

use App\Modules\Shared\Sectors\Sector;

/**
 * مؤشرات نموذجية جاهزة يختار منها المستخدم.
 *
 * الغرض تعليمي قبل أن يكون عمليًا: المستخدم الجديد لا يعرف ما «المؤشر»،
 * فنعرض عليه أمثلة من لغته (مبيعات، عملاء، إعلانات) مع شرح ما يقيسه كل
 * واحد ومثال أرقام — فيفهم الفكرة ويبدأ بضغطة، ثم يضيف مؤشراته الخاصة.
 */
class KpiTemplates
{
    /**
     * @return array<int, array{group: string, items: array<int, array<string, mixed>>}>
     */
    public static function catalog(?string $sector = null): array
    {
        // مجموعة القطاع أولًا: صاحب المدرسة يرى «التسجيل» قبل «المبيعات»،
        // فيفهم أن المنصة تتكلم لغته لا لغة متجر عام (مواصفة التخصص القطاعي).
        $sectorGroup = self::sectorGroup($sector);

        return [
            // `sector` تُمرَّر للقالب ليَسِم المجموعة: تصدُّرها بلا تفسير يبدو
            // ترتيبًا اعتباطيًّا، ومعها يعرف صاحب النشاط أنها ظهرت لأجل قطاعه.
            ...($sectorGroup === null ? [] : [[...$sectorGroup, 'sector' => $sector]]),
            [
                'group' => __('مبيعات وإيراد'),
                'items' => [
                    ['name' => __('المبيعات الشهرية'), 'unit' => __('ريال'),
                        'measures' => __('إجمالي ما تبيعه في الشهر — المقياس الأهم لأي مشروع.'),
                        'example' => __('مثال: من 20,000 اليوم إلى 35,000 خلال ثلاثة أشهر.')],
                    ['name' => __('عدد الطلبات شهريًا'), 'unit' => __('طلب'),
                        'measures' => __('كم عملية بيع تتم في الشهر، بغضّ النظر عن قيمتها.'),
                        'example' => __('مثال: من 40 إلى 70 طلبًا.')],
                    ['name' => __('متوسط قيمة الطلب'), 'unit' => __('ريال'),
                        'measures' => __('كم يدفع العميل في المرة الواحدة — رفعه يزيد الإيراد بلا عملاء جدد.'),
                        'example' => __('مثال: من 150 إلى 220 ريالًا.')],
                ],
            ],
            [
                'group' => __('عملاؤك'),
                'items' => [
                    ['name' => __('العملاء المهتمون شهريًا'), 'unit' => __('عميل'),
                        'measures' => __('كم شخصًا يسأل أو يتواصل معك — قبل أن يشتري.'),
                        'example' => __('مثال: من 30 إلى 60 مهتمًا.')],
                    ['name' => __('العملاء الجدد شهريًا'), 'unit' => __('عميل'),
                        'measures' => __('كم شخصًا اشترى منك لأول مرة هذا الشهر.'),
                        'example' => __('مثال: من 15 إلى 30 عميلًا.')],
                    ['name' => __('تكلفة جلب العميل'), 'unit' => __('ريال'),
                        'measures' => __('كم تصرف حتى يشتري منك عميل واحد — كلما قلّت زاد ربحك.'),
                        'example' => __('مثال: من 90 نزولًا إلى 60 ريالًا.')],
                    ['name' => __('نسبة العملاء العائدين'), 'unit' => '%',
                        'measures' => __('كم من عملائك يعود ويشتري مرة أخرى.'),
                        'example' => __('مثال: من 15% إلى 30%.')],
                ],
            ],
            [
                'group' => __('إعلاناتك'),
                'items' => [
                    ['name' => __('العائد على الإنفاق الإعلاني'), 'unit' => __('ضعف'),
                        'measures' => __('كم ريال إيراد يعود لك مقابل كل ريال تصرفه على الإعلان.'),
                        'example' => __('مثال: من 2 إلى 4 أضعاف.')],
                    ['name' => __('الميزانية الإعلانية الشهرية'), 'unit' => __('ريال'),
                        'measures' => __('كم تصرف على الإعلان شهريًا — لتراقبه مقابل النتيجة.'),
                        'example' => __('مثال: 3,000 ريال.')],
                ],
            ],
            [
                'group' => __('موقعك ومحتواك'),
                'items' => [
                    ['name' => __('زوار الموقع شهريًا'), 'unit' => __('زائر'),
                        'measures' => __('كم شخصًا يصل إلى موقعك أو صفحتك في الشهر.'),
                        'example' => __('مثال: من 800 إلى 2,000 زائر.')],
                    ['name' => __('نسبة التحويل'), 'unit' => '%',
                        'measures' => __('كم من زوّارك يتحول إلى مشترٍ — يكشف قوة صفحتك لا كثرة الزيارات.'),
                        'example' => __('مثال: من 1% إلى 3%.')],
                    ['name' => __('متابعون جدد شهريًا'), 'unit' => __('متابع'),
                        'measures' => __('نمو جمهورك على حساباتك الاجتماعية.'),
                        'example' => __('مثال: من 200 إلى 500 متابع.')],
                ],
            ],
        ];
    }

    /**
     * مؤشرات القطاع المتخصص — القرارات التي يديرها هذا القطاع تحديدًا.
     *
     * @return array{group: string, items: array<int, array<string, mixed>>}|null
     */
    private static function sectorGroup(?string $sector): ?array
    {
        return match ($sector) {
            Sector::EDUCATION => [
                'group' => __('التسجيل والطلاب'),
                'items' => [
                    ['name' => __('استفسارات التسجيل شهريًا'), 'unit' => __('استفسار'),
                        'measures' => __('كم وليّ أمر أو طالبًا يسأل عن التسجيل — أول مؤشرات موسمك.'),
                        'example' => __('مثال: من 25 إلى 60 استفسارًا قبل الموسم.')],
                    ['name' => __('نسبة الاستفسار إلى التسجيل'), 'unit' => '%',
                        'measures' => __('كم من المستفسرين سجّل فعلًا — يكشف قوة الجولة والرد لا الإعلان.'),
                        'example' => __('مثال: من 20% إلى 35%.')],
                    ['name' => __('نسبة إعادة التسجيل'), 'unit' => '%',
                        'measures' => __('كم من طلابك الحاليين يعود العام القادم — أرخص تسجيل تحصل عليه.'),
                        'example' => __('مثال: من 70% إلى 85%.')],
                    ['name' => __('الزيارات والجولات شهريًا'), 'unit' => __('زيارة'),
                        'measures' => __('كم أسرة زارت المدرسة أو حضرت جولة — الخطوة التي تسبق التسجيل غالبًا.'),
                        'example' => __('مثال: من 10 إلى 25 زيارة.')],
                ],
            ],
            Sector::ECOMMERCE => [
                'group' => __('متجرك'),
                'items' => [
                    ['name' => __('نسبة السلات المتروكة'), 'unit' => '%',
                        'measures' => __('كم ممن وضعوا في السلة غادروا دون دفع — أكبر تسرب صامت في المتجر.'),
                        'example' => __('مثال: من 75% نزولًا إلى 60%.')],
                    ['name' => __('تكلفة الطلب من الإعلان'), 'unit' => __('ريال'),
                        'measures' => __('كم تدفع إعلانيًا مقابل كل طلب مكتمل — مقياس صحة الحملة اليومي.'),
                        'example' => __('مثال: من 45 نزولًا إلى 30 ريالًا.')],
                    ['name' => __('الطلبات من البحث المجاني'), 'unit' => __('طلب'),
                        'measures' => __('كم طلبًا يأتي من جوجل بلا إعلان — الأصل الذي يتراكم لصالحك.'),
                        'example' => __('مثال: من 5 إلى 20 طلبًا شهريًا.')],
                ],
            ],
            Sector::REAL_ESTATE => [
                'group' => __('استفساراتك ومعايناتك'),
                'items' => [
                    ['name' => __('الاستفسارات العقارية شهريًا'), 'unit' => __('استفسار'),
                        'measures' => __('كم عميلًا جادًّا تواصل عن وحدة أو مشروع هذا الشهر.'),
                        'example' => __('مثال: من 40 إلى 90 استفسارًا.')],
                    ['name' => __('نسبة الاستفسار إلى المعاينة'), 'unit' => '%',
                        'measures' => __('كم من المستفسرين وصل إلى معاينة — العقار يُباع في المعاينة لا في الإعلان.'),
                        'example' => __('مثال: من 10% إلى 20%.')],
                    ['name' => __('الصفقات المغلقة شهريًا'), 'unit' => __('صفقة'),
                        'measures' => __('كم عقد بيع أو إيجار أُغلق فعلًا.'),
                        'example' => __('مثال: من 3 إلى 6 صفقات.')],
                    ['name' => __('الاستفسارات من قنواتك المملوكة'), 'unit' => '%',
                        'measures' => __('كم من استفساراتك يأتي من موقعك وحساباتك لا من البوابات — مقياس استقلالك عنها.'),
                        'example' => __('مثال: من 15% إلى 35%.')],
                ],
            ],
            default => null,
        };
    }
}
