<?php

declare(strict_types=1);

namespace App\Support\Failures;

/**
 * تصنيف العطل بمن يملك حلّه — لا بموضعه في الكود.
 *
 * هذا التصنيف هو ثابت INV-8 منفَّذًا: العطل الذي سببه لدينا يُصاغ بلغتنا،
 * ولا يُطلب من المستخدم فعل شيء حياله، ولا يُخصم منه رصيد بسببه. خلط
 * الثلاثة في رسالة واحدة هو ما جعل شاشة تقول «رصيدك ٠» بينما الفوترة
 * تقول «٩٩٩٦٧ متاح»: رسالة عطل مزوّد قُرئت كأنها رسالة رصيد.
 */
enum FailureKind: string
{
    /** عطل لدينا: مزوّد، شبكة، طابور. المستخدم لا يملك حياله شيئًا. */
    case Ours = 'ours';

    /** حدّ يخصّ المستخدم: رصيد أو حصة خطة. له إجراء واحد واضح. */
    case Theirs = 'theirs';

    /** نقص أو خطأ في المدخلات. يُصحَّح في الحقل نفسه. */
    case Input = 'input';

    /**
     * هل يُسمح بإجراء مطلوب من المستخدم مع هذا التصنيف؟
     *
     * `ours` يجب أن يكون `user_action = null` دائمًا — وهذا ما يفرضه
     * العقد في `06-api-contract.md` ويثبّته الاختبار.
     */
    public function allowsUserAction(): bool
    {
        return $this !== self::Ours;
    }

    /** هل يُعاد التشغيل تلقائيًا دون تدخل المستخدم؟ */
    public function isAutoRecoverable(): bool
    {
        return $this === self::Ours;
    }
}
