        {--fresh : امسح تشغيلات المشروع السابقة قبل التعبئة}';

    protected $description = 'تعبئة كل الأدوات لمشروع «جِيب لي» لعرض التقرير الكامل الفعلي';

    public function handle(RunToolAction $runTool): int
    {
        $user = User::query()->where('email', $this->option('email'))->first()
            ?? User::query()->orderBy('id')->first();
        if ($user === null) {
            $this->error('لا يوجد مستخدم في النظام.');

            return self::FAILURE;
        }

        $workspace = $this->resolveWorkspace($user);
        if ($workspace === null) {
            $this->error('تعذّر إيجاد مساحة عمل للمستخدم '.$user->email);

            return self::FAILURE;
        }

        $project = Project::query()->firstOrCreate(
            ['workspace_id' => $workspace->id, 'name' => (string) $this->option('project')],
            ['stage' => 4, 'status' => 'active'],
        );

        $inputs = $this->inputs();
        $tools = Tool::query()->whereIn('code', array_keys($inputs))->get()->keyBy('code');

        if ($this->option('fresh')) {
            ToolRun::query()->where('project_id', $project->id)->forceDelete();
            WorkspaceData::query()->where('project_id', $project->id)->delete();
            $this->line('مُسحت تشغيلات المشروع السابقة.');
        }

        $done = 0;
        foreach ($inputs as $code => $data) {
            $tool = $tools->get($code);
            if ($tool === null) {
                $this->warn('أداة غير موجودة في قاعدة البيانات: '.$code);

                continue;
            }
            $runTool->handle($workspace, $project, $tool, $user, 'guided', $data);
            $done++;
            $this->line('  ✓ '.$code);
        }

        $this->newLine();
        $this->info("تمّت تعبئة {$done} أداة لمشروع «{$project->name}».");
        $this->info("workspace_id={$workspace->id} · project_id={$project->id} · actor={$user->email}");
        $this->info("رابط التقرير: /projects/{$project->id}/report");

        return self::SUCCESS;
    }

    private function resolveWorkspace(User $user): ?Workspace
    {
        if ($this->option('workspace')) {
            return Workspace::query()->find($this->option('workspace'));
        }

        return Workspace::query()
            ->whereHas('account', fn ($q) => $q->where('owner_user_id', $user->id))
            ->orderBy('id')->first()
            ?? Workspace::query()
                ->whereHas('members', fn ($q) => $q->where('user_id', $user->id))
                ->orderBy('id')->first();
    }

